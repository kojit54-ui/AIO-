/** 聞き書きの例（台本の形）。架空の会社であることを必ず出す */
export interface Interview {
  /** 例：架空の金属加工会社 */
  who: string;
  lines: { by: "しおり" | "社長"; text: string }[];
}

/** 写真（public/column/ に置く）。実在の会社・製品の写真ではないので、画面に「写真はイメージです」と出す */
export interface ColumnPhoto {
  /** 例：/column/what-to-write-1.webp */
  src: string;
  /** 何が写っているか（読み上げと検索のため） */
  alt: string;
  /** しおりのイラスト（Geminiで作る）。写真の注意書き「写真はイメージです」を付けない */
  illustration?: boolean;
}

/** 「しおりに聞いてみた」：読んでいる社長の質問に、しおりがチャットのように答える。一般的な説明だけ（架空の実績は書かない） */
export interface ChatTurn {
  q: string;
  a: string[];
}

/**
 * 見出しの下に置く、罫線と藍の図や表（HTMLで描く。文字は画像にしない）。
 * 2026-11-08 3AI会議：言葉やしくみの説明は図や表、物や現場は人の顔が写らない写真。写真だけで埋めない。
 */
export type ColumnFigure =
  | { kind: "flow"; title: string; steps: { label: string; note?: string }[]; note?: string }
  | { kind: "table"; title: string; head: [string, string]; rows: [string, string][]; note?: string }
  | {
      kind: "pair";
      title: string;
      left: { label: string; items: string[] };
      right: { label: string; items: string[] };
      /** 片方を「すすめる側」として強く見せるとき。無ければ左右を同じ重さで見せる */
      strong?: "left" | "right";
      note?: string;
    }
  | { kind: "check"; title: string; items: { label: string; note?: string }[]; note?: string };

export interface ColumnSection {
  /** 見出し（社長がAIに聞きそうな問いの形） */
  h: string;
  /** 最初に置く、短い答え */
  answer: string;
  body?: string[];
  list?: string[];
  interview?: Interview;
  /** 見出しのすぐ下に出す写真（物や現場。人の顔は写さない） */
  photo?: ColumnPhoto;
  /** 見出しのすぐ下に出す図や表（言葉やしくみの説明）。photo とどちらか1つ */
  figure?: ColumnFigure;
  /** 箇条書きのあとに出す地の文（別の記事への案内など） */
  after?: string[];
  /** 関連する読みものへの案内（本文の最後に1行。lead のあとに記事名のリンク） */
  see?: { slug: string; lead: string; label: string };
  /** 節の最後に出す「しおりに聞いてみた」 */
  chat?: ChatTurn[];
  /** 見出しの終わりに、しおりが吹き出しでひとこと話す（1記事に1か所。2026-11-09 田村さん「途中でもういっかい出てくるくらいでもよい」）。chat のある見出しには置かない */
  talk?: { mood: IntroMood; text: string };
}

/** 前置きで使うしおりの表情（public/guide/shiori-<表情>.webp）。しょんぼり・怒りは読みものでは使わない */
export const INTRO_MOODS = ["ask", "bow", "cheer", "coffee", "idea", "joy", "point", "right", "surprise", "think", "welldone"] as const;
export type IntroMood = (typeof INTRO_MOODS)[number];

export interface Column {
  slug: string;
  title: string;
  /** 一覧と検索結果に出る、ひとこと */
  lead: string;
  /** YYYY-MM-DD */
  published: string;
  updated: string;
  /** 中身を確かめた日（公式の情報・料金ページと照らした日） */
  checked: string;
  /** 最初に出す「この記事の答え」 */
  summary: string[];
  /** 題名の下に出す写真 */
  hero?: ColumnPhoto;
  /** 冒頭の、しおりの問い（古い型。画面には地の文として出す） */
  opening?: string;
  /** 「この記事の答え」の前に置く、短い前置き（地の文。決まり文句の問いかけにしない） */
  intro?: string;
  /** 前置きを話すときのしおりの表情（2026-11-09 田村さん「出だしをしおりにしゃべらせて。いろんな表情を使おう」）。記事の話に合う顔を選び、続く記事で同じ顔が並ばないようにする */
  introMood?: IntroMood;
  /** 前置きの最後に、急ぐ人向けの見出しへの案内（section は1から数える） */
  jump?: { section: number; lead: string; after: string };
  sections: ColumnSection[];
  /** しおりのひとこと（古い型。画面には出さない） */
  shiori?: string;
  /** 結びの一言。営業の人にそのまま聞ける言葉など、すぐ使える形で終える（2026-11-09 からしおりが吹き出しで話す） */
  closing?: string;
  /** 結びを話すときのしおりの表情（2026-11-09 田村さん「最後の結びもしゃべらせて」）。intro・talk と違う顔にする */
  closingMood?: IntroMood;
  sources?: { label: string; url: string }[];
}

