/** 聞き書きの例（台本の形）。架空の会社であることを必ず出す */
export interface Interview {
  /** 例：架空の金属加工会社 */
  who: string;
  lines: { by: "しおり" | "社長"; text: string }[];
}

export interface ColumnSection {
  /** 見出し（社長がAIに聞きそうな問いの形） */
  h: string;
  /** 最初に置く、短い答え */
  answer: string;
  body?: string[];
  list?: string[];
  interview?: Interview;
}

export interface Column {
  slug: string;
  title: string;
  /** 一覧と検索結果に出る、ひとこと */
  lead: string;
  /** YYYY-MM-DD */
  published: string;
  updated: string;
  /** 中身を確かめた日（公式の情報・料金ページと照らした日） */
  checked: string;
  /** 最初に出す「この記事の答え」 */
  summary: string[];
  /** 冒頭の、しおりの問い（聞く人として1文） */
  opening: string;
  sections: ColumnSection[];
  /** しおりのひとこと（最後に出す） */
  shiori: string;
  sources?: { label: string; url: string }[];
}

