/** 聞き書きの例（台本の形）。架空の会社であることを必ず出す */
export interface Interview {
  /** 例：架空の金属加工会社 */
  who: string;
  lines: { by: "しおり" | "社長"; text: string }[];
}

/** 写真（public/column/ に置く）。実在の会社・製品の写真ではないので、画面に「写真はイメージです」と出す */
export interface ColumnPhoto {
  /** 例：/column/what-to-write-1.webp */
  src: string;
  /** 何が写っているか（読み上げと検索のため） */
  alt: string;
}

/** 「しおりに聞いてみた」：読んでいる社長の質問に、しおりがチャットのように答える。一般的な説明だけ（架空の実績は書かない） */
export interface ChatTurn {
  q: string;
  a: string[];
}

export interface ColumnSection {
  /** 見出し（社長がAIに聞きそうな問いの形） */
  h: string;
  /** 最初に置く、短い答え */
  answer: string;
  body?: string[];
  list?: string[];
  interview?: Interview;
  /** 見出しのすぐ下に出す写真 */
  photo?: ColumnPhoto;
  /** 節の最後に出す「しおりに聞いてみた」 */
  chat?: ChatTurn[];
}

export interface Column {
  slug: string;
  title: string;
  /** 一覧と検索結果に出る、ひとこと */
  lead: string;
  /** YYYY-MM-DD */
  published: string;
  updated: string;
  /** 中身を確かめた日（公式の情報・料金ページと照らした日） */
  checked: string;
  /** 最初に出す「この記事の答え」 */
  summary: string[];
  /** 題名の下に出す写真 */
  hero?: ColumnPhoto;
  /** 冒頭の、しおりの問い（聞く人として1文） */
  opening: string;
  sections: ColumnSection[];
  /** しおりのひとこと（最後に出す） */
  shiori: string;
  sources?: { label: string; url: string }[];
}

