export const LEGAL_DOCS = [TERMS, PRIVACY, TOKUSHOHO];

/** 埋めていない【要確認：…】の数 */
export function countTodos(doc: LegalDoc): number {
  return doc.sections.reduce((n, s) => n + s.items.filter((t) => t.includes(TODO_MARK)).length, 0);
}

/** 利用者の画面に出すリンク。案のあいだは出さない。特商法は有料のプランを始めるまで出さない */
export function legalLinks(opts: { paid?: boolean } = {}): { href: string; label: string }[] {
  if (LEGAL_DRAFT) return [];
  const links = [
    { href: TERMS.path, label: TERMS.title },
    { href: PRIVACY.path, label: PRIVACY.title },
  ];
  if (opts.paid) links.push({ href: TOKUSHOHO.path, label: TOKUSHOHO.title });
  return links;
}

/** ログインせずに読めるページか（利用規約・プライバシーポリシー・特商法の表記） */
export function isLegalPath(pathname: string): boolean {
  return LEGAL_DOCS.some((d) => d.path === pathname);
}
